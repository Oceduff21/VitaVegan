export function translate(locale: Locale, key: string): string {
  const extra = extraDict(locale);
  const profile = profileDict(locale);
  return (
    extra[key] ??
    profile[key] ??
    DICTS[locale][key] ??
    extraDict("en")[key] ??
    profileDict("en")[key] ??
    DICTS.en[key] ??
    DICTS.fr[key] ??
    extraDict("fr")[key] ??
    key
  );
}
