export const LOCALES: { id: Locale; label: string; native: string }[] = [
  { id: "fr", label: "Français", native: "FR" },
  { id: "en", label: "English", native: "EN" },
  { id: "de", label: "Deutsch", native: "DE" },
  { id: "es", label: "Español", native: "ES" },
  { id: "it", label: "Italiano", native: "IT" },
  { id: "nl", label: "Nederlands", native: "NL" },
  { id: "pt", label: "Português", native: "PT" },
  { id: "pl", label: "Polski", native: "PL" },
];

export function isLocale(v: string | null | undefined): v is Locale {
  return !!v && LOCALES.some((l) => l.id === v);
}

export function localeFromBrowser(): Locale {
  if (typeof navigator === "undefined") return "fr";
  const candidates = [navigator.language, ...(navigator.languages ?? [])].map((l) => l.slice(0, 2).toLowerCase());
  return candidates.find(isLocale) ?? "en";
}

